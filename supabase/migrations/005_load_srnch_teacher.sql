select
    2026,
    v.teacher_name,
    v.class_div,
    case
        when count(m.id) = 1 then min(m.id)
        else min(m.id) filter (
            where btrim(coalesce(m.children_group_div, '')) = v.class_div
        )
    end
from pg_temp.teacher_import v
join public.srnch_members m
    on btrim(m.name) = v.student_name
   and upper(btrim(coalesce(m.name_distinct, ''))) = v.name_distinct
group by v.source_row, v.teacher_name, v.class_div
on conflict (year, member_id) do update
set
    teacher_name = excluded.teacher_name,
    class_div = excluded.class_div;
