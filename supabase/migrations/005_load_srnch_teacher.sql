do $$
declare
    missing text;
    ambiguous text;
begin
    with resolved as (
        select
            v.source_row,
            v.raw_name,
            count(m.id) as matched_count,
            count(m.id) filter (
                where btrim(coalesce(m.children_group_div, '')) = v.class_div
            ) as class_count
        from pg_temp.teacher_import v
        left join public.srnch_members m
            on btrim(m.name) = v.student_name
           and upper(btrim(coalesce(m.name_distinct, ''))) = v.name_distinct
        group by v.source_row, v.raw_name, v.class_div
    )
    select
        string_agg(format('%s행 %s', source_row, raw_name), ', ' order by source_row)
            filter (where matched_count = 0),
        string_agg(format('%s행 %s', source_row, raw_name), ', ' order by source_row)
            filter (where matched_count > 1 and class_count <> 1)
    into missing, ambiguous
    from resolved;

    if missing is not null then
        raise exception 'srnch_members에서 찾지 못한 학생: %', missing;
    end if;
    if ambiguous is not null then
        raise exception '이름과 구분이 같은 학생이 여러 명입니다: %', ambiguous;
    end if;
end
$$;

